"""
---------Operatotrs---------
What is an operator?
An operator is a symbol that tells Python to do something with values.
Think about a calculator. You press + to add numbers and - to subtract them.
"""

a = 9
b = 3

print(a + b)
print(a - b)
print(a * b)
print(a / b) #Notice that / gives a floating-point result, even when the answer is a whole number, as in 10 / 2, which gives 5.0.


"""
---------Two special operators---------
1. // (floor division) - gives the whole number part of the quotient

10 // 3 → 3

2. % (modulus) - gives the remainder of the quotient

10 % 3 → 1
"""
print(a // b)
print(a % b)