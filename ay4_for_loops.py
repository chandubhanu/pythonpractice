"""
---------For Loops---------

tep 1: What is a for loop?
A for loop repeats an action for each item in a group.
Imagine you have 3 apples 🍎🍎🍎. You want to count each apple.
Instead of writing print("Apple") three times, Python can do it for you!

You can also write range(start, stop).

"""
for i in range(1,5,2):
    print(i)